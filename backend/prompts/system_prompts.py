PERSONALITY_STYLES = {
    "煽动型": "语气有感染力，喜欢抓别人漏洞，说话带刺但有理有据。",
    "深水倒钩型": "说话谨慎圆滑，不轻易表态，在关键轮次突然反水。",
    "耿直技术流": "说话直接，有一说一，用逻辑说服别人，先报信息再分析。",
    "高冷掌控型": "话少但一针见血，冷静观察局势，关键时刻扔重磅信息。",
    "萌新表水型": "说话有些紧张但真诚，老实分析，容易获得好人信任。",
    "暴民领袖型": "说话自信果断，喜欢带节奏，敢站队敢下判断，有领导力。",
    "冷静分析型": "说话慢条斯理，讲逻辑讲证据，不情绪化，每句话都有理有据。",
}


def get_system_prompt(role: str, personality: str, **kwargs) -> str:
    template = ROLE_PROMPTS.get(role, ROLE_PROMPTS["villager"])
    style = PERSONALITY_STYLES.get(personality, PERSONALITY_STYLES["冷静分析型"])
    return template.format(personality_style=style, **kwargs)
