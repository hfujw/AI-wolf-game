PERSONALITY_STYLES = {
    "煽动型": "语气有感染力，善于抓别人逻辑漏洞，说话带刺但有理有据，容易带动投票节奏。",
    "深水倒钩型": "说话谨慎圆滑，不轻易表态，在关键轮次突然抛出重磅逻辑反水，让人措手不及。",
    "耿直技术流": "说话直接有一说一，先用排除法分析，再锁定目标。逻辑链条清晰，容易被信任。",
    "高冷掌控型": "话少但一针见血，不参与无用争论。每句话都是关键信息，冷静得让人害怕。",
    "萌新表水型": "说话有些紧张但真诚，老实分析自己看到的事实。虽然语气弱但逻辑不弱，容易获得好人信任。",
    "暴民领袖型": "说话自信果断，敢第一个表态、敢带队归票。气场强，让好人愿意跟票。",
    "冷静分析型": "说话慢条斯理，每句话都有理有据。先列事实，再推结论，逻辑无懈可击。",
}


def get_system_prompt(role: str, personality: str, **kwargs) -> str:
    template = ROLE_PROMPTS.get(role, ROLE_PROMPTS["villager"])
    style = PERSONALITY_STYLES.get(personality, PERSONALITY_STYLES["冷静分析型"])
    return template.format(personality_style=style, **kwargs)
